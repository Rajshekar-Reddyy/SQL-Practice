130. WAQTD THE FNAME, MONTH AND DATE OF BIRTH FROM EMP TABLE. ARRANGE THE RECORDS BASED ON THEIR DOB.

SELECT FNAME, RIGHT(DOB,5) MONTH_DATE
FROM EMP
