127. WAQTD THE FULLNAME, SALARY, JOB IF THE EMP FNAME ENDS WITH I USING RIGHT().

SELECT CONCAT(FNAME,' ',LNAME) FULLNAME, SAL, JOB
FROM EMP
WHERE RIGHT(FNAME,1)='I';

128. WAQTD THE FIRST 3 CHARACTERS OF FNAME, LAST 2 CHARACTERS OF LNAME FROM EMP TABLE.

SELECT LEFT(FNAME,3), RIGHT(LNAME,2)
FROM EMP;

129. WAQTD THE DETAILS OF EMP IF THE EMP WAS BORN IN 1995 USING LEFT FUNCTION.

SELECT *
FROM EMP
WHERE LEFT(DOB,4)=1995;

130. WAQTD THE FNAME, MONTH AND DATE OF BIRTH FROM EMP TABLE. ARRANGE THE RECORDS BASED ON THEIR DOB.

SELECT FNAME, RIGHT(DOB,5) MONTH_DATE
FROM EMP
ORDER BY MONTH_DATE;
