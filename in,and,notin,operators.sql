29. WAQTD THE DETAILS OF EMP WHO ARE NOT WORKING IN 110,111 OR 112.

SELECT *
FROM EMP
WHERE DNO!=110 AND DNO!=111 AND DNO!=112;

OR

SELECT *
FROM EMP
WHERE DNO NOT IN (110,111,112);

30. WAQTD THE DETAILS OF EMP IF THE EMP IS WORKING AS TESTER OR DEVELOPER BUT NOT IN DEPT 110 OR 112.

SELECT *
FROM EMP
WHERE JOB IN ('TESTER','DEVELOPER') AND DNO NOT IN (110,112);

