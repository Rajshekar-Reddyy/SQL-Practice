203. WAQTD THE EMP FULL NAME AND DEPT NAME IF THE EMP IS WORKING AS SALESMAN.

SELECT CONCAT(E.FNAME,' ',E.LNAME) FULLNAME,D.DNAME
FROM EMP E INNER JOIN DEPT D
ON E.DNO=D.DNO
WHERE E.JOB='SALESMAN';

204. WAQTD THE DEPT NAME AND ITS LOCATION.

SELECT D.DNAME,L.LOCATION
FROM DEPT D INNER JOIN LOCATION L
ON D.LID=L.LID;

205. WAQTD THE EMP FIRST NAME, DEPT NAME, JOB, SAL IF THE EMP FNAME START WITH VOWELS.

SELECT E.FNAME, D.DNAME, E.JOB,E.SAL
FROM EMP E INNER JOIN DEPT D
ON E.DNO=D.DNO
WHERE LEFT(E.FNAME,1)IN('A','E','I','O','U');

