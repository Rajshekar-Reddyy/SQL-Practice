131. WAQTD THE AVG SALARY IN EVERY DEPT. ROUND OFF THE AVG SALARY TO 100'S PLACE.

SELECT ROUND(AVG(SAL),-2),DNO
FROM EMP
GROUP BY DNO;

132. WAQTD THE DETAILS OF EMP WHO HAVE EVEN EID.

SELECT *
FROM EMP
