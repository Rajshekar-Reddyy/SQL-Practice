133. WAQTD THE EMP FNAME, JOB, SALARY IF THE EMP FNAME CONTAINS EVEN LENGTH.

SELECT FNAME,JOB,SAL
FROM EMP
WHERE MOD(LENGTH(FNAME),2)=0;

