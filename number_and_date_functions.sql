139. WAQTD THE EMP FNAME, DOJ IF THE EMP WAS JOINED IN LEAP YEAR.
{Hint :
 * Year must be divisible 4 or 400 but not divisible by 100.
}

SELECT FNAME,DOJ
FROM EMP
WHERE 
(MOD(YEAR(DOJ),4)=0 OR MOD(YEAR(DOJ),400)=0) AND 
MOD(YEAR(DOJ),100)!=0;

140. WAQTD THE NUMBER OF EMPS HIRED EVERY YEAR.

SELECT YEAR(DOJ),COUNT(*)
FROM EMP
GROUP BY YEAR(DOJ);

141. WAQTD THE FNAME, YEAR OF EXPERIENCE FROM EMP TABLE.

SELECT FNAME, YEAR(CURDATE())-YEAR(DOJ) EXPERIENCE
FROM EMP;

142. WAQTD THE FNAME, MONTH-DATE OF THE EMP WHO HAVE THEIR NEAREST 3 UPCOMING BIRTHDAYS.

SELECT FNAME,DATE_FORMAT(DOB,'%m-%d') BIRTH_DAY
FROM EMP
WHERE DATE_FORMAT(CURDATE(),'%m-%d')<DATE_FORMAT(DOB,'%m-%d')
ORDER BY BIRTH_DAY
LIMIT 3;

143. WAQTD THE CURRENT AGE OF ALL THE EMPS. (in number of years).

SELECT FNAME, YEAR(CURDATE())-YEAR(DOB) AGE
FROM EMP;
